#!/usr/bin/env python3
"""Compile native name-based resource contracts into checked Java references."""
import argparse, re, xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'app/src/main'
target = source / 'java/dev/fourwags/sumi/inputmethod/keyboard/internal/BundledKeyboardResources.java'
strings = {e.get('name') for p in (source/'res/values').glob('*.xml')
           for e in ET.parse(p).getroot() if e.tag == 'string'}
labels = {name for p in source.rglob('*') if p.is_file() and p.suffix in ('.java', '.xml')
          for name in re.findall(r'!string/([a-zA-Z0-9_]+)', p.read_text())}
assert labels <= strings, 'Missing native keyboard label resource: ' + str(labels - strings)
arrays = {e.get('name'): [item.text for item in e] for p in (source/'res/values').glob('*.xml')
          for e in ET.parse(p).getroot() if e.tag == 'string-array'}
required = set(labels)
for name in arrays['predefined_layouts']:
    required |= {'subtype_generic_' + name, 'subtype_no_language_' + name}
for name in arrays['subtype_locale_exception_keys']:
    required |= {'subtype_' + name, 'subtype_with_layout_' + name}
for name in arrays['subtype_locale_displayed_in_root_locale']:
    required.add('subtype_in_root_locale_' + name)
# These inherited, unexposed layout/locale entries never had labels upstream.
# Preserve their zero-result contract; English-US/QWERTY is always required.
legacy_optional = {'subtype_generic_halmak', 'subtype_no_language_halmak', 'subtype_with_layout_hu_ZZ'}
assert (required - legacy_optional) <= strings, 'Missing subtype/label resource contract: ' + str(required - strings - legacy_optional)
assert {'subtype_en_US', 'subtype_generic_qwerty', 'subtype_no_language_qwerty'} <= strings

groups = {'layout': sorted(p.stem for p in (source/'res/xml').glob('keyboard_layout_set_*.xml')),
          'string': sorted({s for s in strings if s.startswith('subtype_')} | labels)}
lines = ['// Generated by tools/generate_keyboard_resources.py; do not edit.',
         'package dev.fourwags.sumi.inputmethod.keyboard.internal;',
         'import dev.fourwags.sumi.inputmethod.latin.R;',
         'public final class BundledKeyboardResources {',
         '    private BundledKeyboardResources() {}']
for method, names in groups.items():
    lines += [f'    public static int {method}(String name) {{', '        if (name == null) return 0;']
    if method == 'string': lines += ['        if (name.startsWith("string/")) name = name.substring(7);']
    lines += ['        switch (name) {']
    kind = 'xml' if method == 'layout' else 'string'
    lines += [f'            case "{name}": return R.{kind}.{name};' for name in names]
    lines += ['            default: return 0;', '        }', '    }']
lines += ['}', '']
result = '\n'.join(lines)
parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
if args.check:
    assert target.read_text() == result, 'Bundled keyboard resource map is stale; regenerate it'
else: target.write_text(result)
print(f'Bundled keyboard resource map verified: {len(groups["layout"])} layouts, {len(groups["string"])} strings')
