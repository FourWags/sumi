#!/usr/bin/env python3
"""Generate compile-time references for bundled spoken key descriptions."""
from pathlib import Path
import argparse,xml.etree.ElementTree as E
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
project=Path(__file__).resolve().parents[1]
prefixes=('spoken_accented_letter_','spoken_symbol_','spoken_emoji_','spoken_emoticon_')
names=sorted({node.attrib['name'] for path in (project/'app/src/main/res/values').glob('*.xml') for node in E.parse(path).getroot().findall('string') if node.attrib['name'].startswith(prefixes)})
chunks=[names[i:i+200] for i in range(0,len(names),200)]
s='''// Generated by tools/generate_spoken_key_resources.py; do not edit by hand.
package dev.fourwags.sumi.inputmethod.accessibility;

import dev.fourwags.sumi.inputmethod.latin.R;
import java.util.Collections;
import java.util.HashMap;
import java.util.Map;

final class SpokenKeyResources {
    private static final Map<String, Integer> IDS = build();
    private SpokenKeyResources() {}
    static int find(String name) {
        Integer id = IDS.get(name);
        return id == null ? 0 : id;
    }
    private static Map<String, Integer> build() {
        Map<String, Integer> ids = new HashMap<>();
'''
for i in range(len(chunks)):s+=f'        add{i}(ids);\n'
s+='        return Collections.unmodifiableMap(ids);\n    }\n'
for i,chunk in enumerate(chunks):
 s+=f'    private static void add{i}(Map<String, Integer> ids) {{\n'
 for name in chunk:s+=f'        ids.put("{name}", R.string.{name});\n'
 s+='    }\n'
s+='}\n';target=project/'app/src/main/java/dev/fourwags/sumi/inputmethod/accessibility/SpokenKeyResources.java'
if a.check:assert target.read_text()==s,'Spoken-key references are stale; run generator'
else:target.write_text(s)
print(f'{len(names)} spoken resources: '+('verified' if a.check else 'generated'))
